namespace SkyW.Abstractions.Logging;

/// <summary>
/// Уровень важности сообщения: чем позже объявлен, тем важнее.
/// </summary>
/// <remarks>
/// Порядок объявления значим: фильтр журнала — это сравнение, а не набор масок.
/// Объявлен в слое 1, чтобы приёмники не попадали в прикладной код
/// (docs/engine-architecture.md раздел 1.2).
/// </remarks>
public enum LogLevel
{
    /// <summary>Детализация для диагностики, по умолчанию выключена.</summary>
    Debug = 0,

    /// <summary>Обычный ход работы: сцена загружена, тело создано.</summary>
    Information = 1,

    /// <summary>Условия не штатные, работа продолжается: исчерпан бюджет кадра.</summary>
    Warning = 2,

    /// <summary>Работа нарушена: сцена не собралась, ресурс не найден.</summary>
    Error = 3,
}